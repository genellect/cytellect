"""Regenerable duplicates omitted from ``seed.zip`` and their byte-exact restoration.

The API keeps every uploaded plane twice: the original TIFF (``ch<N>.tif``) and
its decoded array (``channel-<id>.npy``). Detector engine directories also keep
copies of their input arrays (for example ``cellpose-input.npy``). The seed
stores each such duplicate once and lists the others in ``showcase.json``
under ``regenerate``:

- ``{"path", "decode_tiff": <tif path>, "sha256", "bytes"}``: decode with the
  API's own ``read_tiff`` and write with ``numpy.save``, exactly as the upload
  route does;
- ``{"path", "copy_of": <path>, "sha256", "bytes"}``: byte copy of a file kept in
  the archive or restored earlier in the list (for example the planes the Fiji
  engine writes, identical to the uploaded TIFFs).

``restore`` must run after unzipping and before the API opens the data
directory. Every regenerated file is checked against its recorded SHA-256;
any difference raises ``showcase_seed_restore_mismatch``.
"""
from __future__ import annotations

import hashlib
import json
import shutil
from pathlib import Path, PurePosixPath

MANIFEST = "showcase.json"


def _digest(path: Path) -> str:
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def _inside(root: Path, relative: str) -> Path:
    pure = PurePosixPath(relative)
    if pure.is_absolute() or ".." in pure.parts:
        raise ValueError("showcase_seed_path_invalid")
    return root.joinpath(*pure.parts)


def plan(files: dict[str, Path], channel_arrays: dict[str, str], minimum_bytes: int = 65536) -> list[dict]:
    """Build-time: list duplicates among seed ``files`` given ``{npy name: tif name}``.

    Channel arrays are regenerated from their TIFF; any other file of at least
    ``minimum_bytes`` that is a byte copy of a kept or regenerated file is
    regenerated by copying it. The caller omits every listed path from the archive.
    """
    import numpy as np
    from cytellect_analysis.images import read_tiff

    entries: list[dict] = []
    by_digest: dict[str, str] = {}
    for npy, tif in sorted(channel_arrays.items()):
        path = files[npy]
        digest = _digest(path)
        # Refuse to omit a file that the documented regeneration would not reproduce.
        check = path.with_name(path.name + ".restore-check.npy")
        np.save(check, read_tiff(files[tif]), allow_pickle=False)
        reproducible = _digest(check) == digest
        check.unlink()
        if not reproducible:
            continue
        by_digest.setdefault(digest, npy)
        entries.append({"path": npy, "decode_tiff": tif, "sha256": digest, "bytes": path.stat().st_size})
    # Any other byte-identical large file (engine copies of input planes, the same
    # detection copy in a run and in its recording) is kept once and copied back.
    regenerated = {entry["path"] for entry in entries}
    for name, path in sorted(files.items()):
        if name in regenerated or path.stat().st_size < minimum_bytes:
            continue
        digest = _digest(path)
        if digest in by_digest:
            entries.append({"path": name, "copy_of": by_digest[digest], "sha256": digest,
                            "bytes": path.stat().st_size})
        else:
            by_digest[digest] = name
    return entries


def restore(data_dir: Path) -> int:
    """Recreate every listed duplicate in an unzipped seed; returns the count."""
    import numpy as np
    from cytellect_analysis.images import read_tiff

    root = Path(data_dir)
    manifest_path = root / MANIFEST
    entries = json.loads(manifest_path.read_text(encoding="utf-8")).get("regenerate", [])
    for entry in entries:
        target = _inside(root, entry["path"])
        target.parent.mkdir(parents=True, exist_ok=True)
        if "decode_tiff" in entry:
            pixels = read_tiff(_inside(root, entry["decode_tiff"]))
            np.save(target, pixels, allow_pickle=False)
        else:
            shutil.copyfile(_inside(root, entry["copy_of"]), target)
        if target.stat().st_size != entry["bytes"] or _digest(target) != entry["sha256"]:
            raise ValueError("showcase_seed_restore_mismatch")
    return len(entries)
