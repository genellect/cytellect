def _t_critical(df):
    """Invert Student tail via beta identity; do not call product/scipy.stats."""
    low, high = 0.0, 1e6
    for _ in range(120):
        mid = (low + high) / 2
        tail = 0.5 * betainc(df / 2, 0.5, df / (df + mid * mid))
        if tail > 0.025:
            low = mid
        else:
            high = mid
    return (low + high) / 2


def _mean_interval(values):
    mean = statistics.mean(values)
    sd = statistics.stdev(values)
    half = _t_critical(len(values) - 1) * sd / math.sqrt(len(values))
    return [mean, mean - half, mean + half, sd]


def _welch(control, treatment):
    a = statistics.variance(control) / len(control)
    b = statistics.variance(treatment) / len(treatment)
    df = (a + b) ** 2 / (a * a / (len(control) - 1) + b * b / (len(treatment) - 1))
    difference = statistics.mean(treatment) - statistics.mean(control)
    half = _t_critical(df) * math.sqrt(a + b)
    return [difference, difference - half, difference + half]


def _numerical_oracle():
    control, treatment = [2.0, 4.0, 8.0], [3.0, 8.0, 10.0]
    differences = [t - c for c, t in zip(control, treatment, strict=True)]
    log_ratios = [math.log(t / c) for c, t in zip(control, treatment, strict=True)]
    wc, wt = [1.0, 3.0], [2.0, 4.0, 6.0]
    return {
        "paired_control": control,
        "paired_treatment": treatment,
        "paired_differences": differences,
        "paired_difference": _mean_interval(differences)[:3],
        "paired_ratio": [math.exp(x) for x in _mean_interval(log_ratios)[:3]],
        "control_summary": _mean_interval(control),
        "treatment_summary": _mean_interval(treatment),
        "welch_control": wc, "welch_treatment": wt,
        "welch_difference": _welch(wc, wt),
        "welch_ratio": [math.exp(x) for x in _welch(list(map(math.log, wc)), list(map(math.log, wt)))],
        "fraction_differences_pp": [25.0, -25.0, 50.0],
        "fraction_difference": _mean_interval([25.0, -25.0, 50.0])[:3],
        "scalar_field": {"nucleus_count": 4, "evaluable_count": 3,
                         "positive_count": 2, "positive_fraction": 2 / 3,
                         "non_evaluable_count": 1},
        "empty_field": {"nucleus_count": 0, "positive_count": 0,
                        "positive_fraction": None, "reason": "no_evaluable_nuclei"},
        "failed_or_excluded": {"value": None, "nucleus_count": None},
        "unknown_calibration_reason": "calibration_unknown",
        "no_objects_reason": "no_nucleolus",
        "one_pixel_reason": "degenerate_objects",
        "zero_variance_reason": "zero_variance",
        "rank_reason": "rank_test",
        "nonpositive_reason": "nonpositive_values",
    }


def _public_masks():
    manifest = json.loads((FIXTURE / "manifest.json").read_text(encoding="utf-8"))
    for item in manifest["images"]:
        path = FIXTURE / item["mask"]["path"]
        assert hashlib.sha256(path.read_bytes()).hexdigest() == item["mask"]["sha256"]
        pixels = np.asarray(Image.open(path))
        pixels = pixels[..., 0] if pixels.ndim == 3 else pixels
        yield item["id"], label(pixels, connectivity=2).astype(np.uint32)


def _shape_oracle(mask):
    """Closed-form eigenvalues of 2x2 population covariance of real contours."""
    objects = []
    for region_id in np.unique(mask):
        if not region_id:
            continue
        y, x = np.nonzero(mask == region_id)
        dx, dy = x.astype(float) - x.mean(), y.astype(float) - y.mean()
        xx, yy, xy = float(np.mean(dx * dx)), float(np.mean(dy * dy)), float(np.mean(dx * dy))
        discriminant = math.hypot(xx - yy, 2 * xy)
        largest, smallest = (xx + yy + discriminant) / 2, (xx + yy - discriminant) / 2
        eccentricity = math.sqrt(max(0, 1 - smallest / largest)) if largest > 0 else None
        border = bool(np.any(x == 0) or np.any(y == 0) or np.any(x == mask.shape[1] - 1)
                      or np.any(y == mask.shape[0] - 1))
        objects.append([int(region_id), len(x), eccentricity, border])
    measured = [row for row in objects if row[2] is not None]
    return {"objects": objects, "nucleus_count": len(objects),
            "border_count": sum(row[3] for row in objects),
            "area_weighted_eccentricity": sum(row[1] * row[2] for row in measured) / sum(row[1] for row in measured),
            "shape": list(mask.shape)}


if __name__ == "__main__":
    print(json.dumps({"numeric": _numerical_oracle(),
                      "public": {name: _shape_oracle(mask) for name, mask in _public_masks()}}, indent=2))


